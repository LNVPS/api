CREATE TABLE vm_migration (
    id INTEGER UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    vm_id INTEGER UNSIGNED NOT NULL,
    source_host_id INTEGER UNSIGNED NOT NULL,
    source_disk_id INTEGER UNSIGNED NOT NULL,
    target_host_id INTEGER UNSIGNED NOT NULL,
    target_disk_id INTEGER UNSIGNED NOT NULL,
    state SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    phase VARCHAR(50) NOT NULL DEFAULT '',
    options TEXT NOT NULL,
    old_ips TEXT,
    source_retained BIT(1) NOT NULL DEFAULT 0,
    needs_attention BIT(1) NOT NULL DEFAULT 0,
    source_was_running BIT(1) NOT NULL DEFAULT 0,
    flipped BIT(1) NOT NULL DEFAULT 0,
    bytes_copied BIGINT UNSIGNED NOT NULL DEFAULT 0,
    checksum VARCHAR(128),
    error TEXT,
    initiated_by INTEGER UNSIGNED,
    created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    finished DATETIME,
    active_vm_id INTEGER UNSIGNED GENERATED ALWAYS AS (IF(state = 0, vm_id, NULL)) STORED,
    UNIQUE KEY uq_vm_migration_active (active_vm_id),
    INDEX ix_vm_migration_vm (vm_id),
    CONSTRAINT fk_vm_migration_vm FOREIGN KEY (vm_id) REFERENCES vm (id) ON DELETE CASCADE
);
